#!/bin/sh
# Compiles the post-effect shaders to SPIR-V and writes ../shaders_spv.h (committed, so a build needs no glslc).
# Run after editing any shader: ./build.sh
set -e
cd "$(dirname "$0")"
GLSLC=$(ls -d ~/Library/Android/sdk/ndk/*/shader-tools/*/glslc 2>/dev/null | tail -1)
OUT=../shaders_spv.h
echo "// Generated by shaders/build.sh from shaders/*.vert|frag. Do not edit." > $OUT
echo "#pragma once" >> $OUT
echo "#include <stdint.h>" >> $OUT
for f in quad.vert copy.frag thresh.frag grain.frag drop.vert drop.frag; do
  name=$(echo "$f" | tr '.' '_')
  "$GLSLC" --target-env=vulkan1.0 -O -mfmt=num -o "/tmp/$name.inc" "$f"
  echo "static const uint32_t kSpv_$name[] = {" >> $OUT
  cat "/tmp/$name.inc" >> $OUT
  echo "};" >> $OUT
done
